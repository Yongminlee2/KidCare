package com.kidcare.family.logic

/**
 * 보호자 화면 맨 위의 "애기폰이 대답하지 않아요" 배너를 띄울지 판정한다.
 *
 * ## 왜 판정 재료를 바꿨나
 *
 * 옛 판정은 "마지막 상태 신호가 30분 넘게 안 바뀌면"이었다. 그 신호를 만들던 것은
 * 아이 폰이 위치를 올릴 때마다 함께 쓰던 주기적 상태 쓰기인데, 무료 한도 때문에
 * 그 주기적 쓰기 자체가 없어졌다(docs/known-issues.md 12번). 그 판정을 그대로 두면
 * **완전히 정상인 폰이 30분마다 무조건 끊긴 것으로 보인다** — 기능이 정확히 반대로
 * 동작한다.
 *
 * 그렇다고 배너를 지울 수는 없다. 이 배너가 알리려던 사고(아이가 앱을 강제 종료해
 * 명령 리스너·알람·위치 수집이 한꺼번에 멎은 상태, known-issues 8번)는 그대로
 * 남아 있고, 여전히 부모 눈에 안 보인다. 그래서 재료를 **"침묵의 길이"에서
 * "물어봤는데 대답이 없는가"로** 바꿨다.
 *
 * ## 세 조건을 모두 만족해야 띄운다
 *
 * 1. **한 번이라도 물어본 적이 있다** ([lastRequestAt] > 0). 페어링만 끝내고 아직
 *    '지금 위치 확인'을 한 번도 안 누른 부모에게 "연결이 끊겼어요"라고 말하는 것은
 *    거짓말이다. 물어본 적 없는 폰은 대답하지 않은 것이 아니다.
 * 2. **마지막 물음 뒤로 대답이 없다** ([lastAnswerAt] < [lastRequestAt]).
 * 3. **그 물음이 [THRESHOLD_MILLIS] 넘게 묵었다.** 한 번의 무응답(터널, Doze 창,
 *    절전 낮잠)만으로 배너를 띄우면 멀쩡한 폰에 헛경보가 나고, 그러면 부모가 이
 *    문구를 곧 안 읽게 된다 — 정작 진짜로 강제 종료된 날에도.
 *
 * 세 값은 **모두 부모 폰 자기 시계**여야 한다. [lastRequestAt]·[lastAnswerAt] 은
 * 부모 폰이 직접 적은 값이므로, 같은 시계로 잰 `now` 와 빼면 폰 시계가 얼마나
 * 어긋나 있든 차이 자체는 정확하다. 여기에 서버 보정 시각을 섞으면 오히려 보정
 * 오차가 그대로 오차로 들어온다.
 *
 * 안드로이드 API 에 의존하지 않는다. JVM 단위 테스트 대상.
 */
object DisconnectRule {

    /**
     * 이만큼 대답이 없으면 "끊겼다"고 본다.
     *
     * 30분은 옛 판정에서 쓰던 값 그대로다. 근거도 그대로다 — 늦게 알리는 쪽이
     * 헛되이 알리는 쪽보다 낫다. 명령 화면의 60초 무응답 표시와 역할이 다르다:
     * 60초는 "방금 누른 그 명령"에 대한 답이고, 이 배너는 "이 폰이 통째로 죽어
     * 있다"에 대한 답이다.
     */
    const val THRESHOLD_MILLIS: Long = 30 * 60 * 1000L

    fun isDisconnected(lastRequestAt: Long, lastAnswerAt: Long, nowMillis: Long): Boolean =
        lastRequestAt > 0L &&
            lastAnswerAt < lastRequestAt &&
            nowMillis - lastRequestAt >= THRESHOLD_MILLIS
}
